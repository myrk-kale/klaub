#!/bin/sh
#
# Prints the Homebrew formula for a released version of klaub.
#
#   packaging/render-formula.sh VERSION SHA_AARCH64_DARWIN SHA_X86_64_DARWIN SHA_AARCH64_LINUX SHA_X86_64_LINUX
#
# The shas are the SHA-256 digests published next to each release archive. The release workflow
# (.github/workflows/homebrew.yml) runs this and pushes the result to myrk-kale/homebrew-tap, at
# Formula/klaub.rb, so that `brew install myrk-kale/tap/klaub` works on macOS and on Linux.

set -eu

[ "$#" -eq 5 ] || { echo "usage: $0 VERSION SHA_AARCH64_DARWIN SHA_X86_64_DARWIN SHA_AARCH64_LINUX SHA_X86_64_LINUX" >&2; exit 2; }

version="$1"
darwin_arm="$2"
darwin_intel="$3"
linux_arm="$4"
linux_intel="$5"

for sha in "$darwin_arm" "$darwin_intel" "$linux_arm" "$linux_intel"; do
  case "$sha" in
    *[!0-9a-f]* | "") echo "error: not a SHA-256 digest: $sha" >&2; exit 2 ;;
  esac
  [ "${#sha}" -eq 64 ] || { echo "error: not a SHA-256 digest: $sha" >&2; exit 2; }
done

base="https://github.com/myrk-kale/klaub/releases/download/v${version}"

cat <<FORMULA
# Generated by packaging/render-formula.sh in https://github.com/myrk-kale/klaub. Do not edit here.

class Klaub < Formula
  desc "Terminal code reviewer for the human reading AI-written code"
  homepage "https://github.com/myrk-kale/klaub"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/klaub-${version}-aarch64-apple-darwin.tar.gz"
      sha256 "${darwin_arm}"
    end
    on_intel do
      url "${base}/klaub-${version}-x86_64-apple-darwin.tar.gz"
      sha256 "${darwin_intel}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/klaub-${version}-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "${linux_arm}"
    end
    on_intel do
      url "${base}/klaub-${version}-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "${linux_intel}"
    end
  end

  def install
    bin.install "klaub"
    prefix.install "LICENSE", "README.md", "CHANGELOG.md", "THIRD-PARTY-NOTICES.md"
    pkgshare.install "licenses", "dependencies.txt"
  end

  test do
    assert_match "klaub ${version}", shell_output("#{bin}/klaub version")
  end
end
FORMULA
