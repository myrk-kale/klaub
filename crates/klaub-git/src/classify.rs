//! Deciding what a blob is: text, binary or generated.

use std::sync::Arc;

use klaub_core::path::RepoPath;
use klaub_core::snapshot::Blob;

/// How many leading bytes are inspected for NUL when sniffing binary content.
const SNIFF_BYTES: usize = 8192;

/// Builds a [`Blob`] from raw bytes: UTF-8 text without NUL bytes is text, anything else binary.
pub(crate) fn blob_from_bytes(bytes: &[u8]) -> Blob {
    let head = &bytes[..bytes.len().min(SNIFF_BYTES)];
    if !head.contains(&0)
        && let Ok(text) = std::str::from_utf8(bytes)
    {
        return Blob::text(Arc::<str>::from(text));
    }
    Blob::binary(bytes.len() as u64, blake3::hash(bytes).to_hex().to_string())
}

const GENERATED_FILES: &[&str] = &[
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "Cargo.lock",
    "poetry.lock",
    "Pipfile.lock",
    "go.sum",
    "composer.lock",
    "Gemfile.lock",
];
const GENERATED_SUFFIXES: &[&str] = &[
    ".min.js",
    ".min.css",
    ".map",
    ".pb.go",
    "_pb2.py",
    "_pb2_grpc.py",
    ".generated.ts",
];
const GENERATED_DIRS: &[&str] = &[
    "node_modules",
    "vendor",
    "dist",
    "build",
    "__pycache__",
    ".next",
];
const GENERATED_MARKERS: &[&str] = &[
    "@generated",
    "DO NOT EDIT",
    "Code generated",
    "auto-generated",
    "autogenerated",
];

/// Whether a file looks machine-generated, by name, location or a marker in its first lines.
pub(crate) fn looks_generated(path: &RepoPath, text: Option<&str>) -> bool {
    let name = path.file_name();
    if GENERATED_FILES.contains(&name)
        || GENERATED_SUFFIXES
            .iter()
            .any(|suffix| name.ends_with(suffix))
    {
        return true;
    }
    if GENERATED_DIRS
        .iter()
        .any(|dir| path.is_within(dir) || path.as_str().contains(&format!("/{dir}/")))
    {
        return true;
    }
    text.is_some_and(|text| {
        let head: String = text.lines().take(5).collect::<Vec<_>>().join("\n");
        GENERATED_MARKERS.iter().any(|marker| head.contains(marker))
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use klaub_core::snapshot::ContentKind;

    fn path(p: &str) -> RepoPath {
        RepoPath::new(p).unwrap()
    }

    #[test]
    fn classifies_text_and_binary() {
        assert_eq!(
            blob_from_bytes("héllo\n".as_bytes()).kind(),
            ContentKind::Text
        );
        assert_eq!(blob_from_bytes(b"").kind(), ContentKind::Text);
        assert_eq!(blob_from_bytes(b"abc\0def").kind(), ContentKind::Binary);
        assert_eq!(
            blob_from_bytes(&[0xff, 0xfe, 0x41]).kind(),
            ContentKind::Binary,
            "invalid UTF-8"
        );
    }

    #[test]
    fn detects_generated_files() {
        assert!(looks_generated(&path("package-lock.json"), None));
        assert!(looks_generated(&path("web/app.min.js"), None));
        assert!(looks_generated(&path("api/service_pb2.py"), None));
        assert!(looks_generated(&path("node_modules/x/index.js"), None));
        assert!(looks_generated(&path("web/dist/main.js"), None));
        assert!(looks_generated(
            &path("src/schema.rs"),
            Some("// Code generated by tool. DO NOT EDIT.\nfn x() {}")
        ));
        assert!(!looks_generated(&path("src/main.rs"), Some("fn main() {}")));
        assert!(!looks_generated(&path("src/distance.py"), None));
    }

    #[test]
    fn markers_deep_in_the_file_do_not_count() {
        let late = format!("{}// DO NOT EDIT\n", "x\n".repeat(20));
        assert!(!looks_generated(&path("a.py"), Some(&late)));
    }
}
